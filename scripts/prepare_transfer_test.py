def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def prepare():
    objects, cases = [], []

    def add(kind, name, description, basic=None, difficult=None, aliases=None):
        object_id = "transfer-v1-" + hashlib.sha256((kind + ":" + name).encode()).hexdigest()[:20]
        obj = {"object_id": object_id, "name": name, "kind": kind, "description": description, "aliases": aliases or []}
        objects.append(obj)
        if basic is not None:
            cases.append({"object": obj, "basic": basic, "difficult": difficult})

    for name, description, basic, difficult in APPS:
        add("app", name, description, basic, difficult, ["Morsel"] if name == "Морсель" else [])
    for index, purpose in enumerate(DISTRACTORS, 1):
        for mode in ("персональный", "общий"):
            add("app", f"Журек-{index:02d} — {mode}", f"{purpose}. Режим данных: {mode}.")
    projects = ["Кленовый маяк", "Вечерний атлас", "Синий парус", "Тихий склон", "Звонкий камень"]
    for project in projects:
        add("folder", f"{project} — чертежи", f"Папка с исходными чертежами проекта {project}.",
            f"Открой папку с чертежами проекта {project}",
            f"Мне не нужен отдельный PDF: открой весь каталог исходных чертежей проекта {project}")
        add("folder", f"{project} — измерения", f"Папка таблиц измерений проекта {project}.",
            f"Нужна папка с таблицами измерений по проекту {project}",
            f"Не чертежи и не фотографии; покажи каталог измерений проекта {project}")
        add("folder", f"{project} — фотографии", f"Папка фотографий проекта {project}.")
        add("folder", f"{project} — архивы", f"Папка старых архивов проекта {project}.")
    for index, topic in enumerate(("Схема питания", "Геоточки участка", "План расстановки", "Спецификация узла", "График поставок", "Список деталей")):
        project = projects[index % len(projects)]
        for suffix, description in (("pdf", "Утверждённая итоговая версия в PDF"),
                                    ("docx", "Рабочий редактируемый черновик"),
                                    ("zip", "Архив исходных материалов")):
            name = f"{project} — {topic}.{suffix}"
            if index < 5 and suffix == "pdf":
                add("file", name, f"{description}: {topic}, проект {project}.",
                    f"Открой итоговый PDF «{topic}» проекта {project}",
                    f"Не черновик DOCX и не архив. Нужен утверждённый файл «{topic}» проекта {project} в PDF")
            else:
                add("file", name, f"{description}: {topic}, проект {project}.")
    require(Counter(o["kind"] for o in objects) == {"app": 139, "folder": 20, "file": 18}, "Catalog density changed")
    require(len(cases) == 50 and len({o["object_id"] for o in objects}) == 177, "Wrong cases or duplicate IDs")
    require(all(set(o) == OBJECT_FIELDS for o in objects), "Host execution fields entered the test")
    training = [r for name in ("launcher-train-v1", "launcher-stt-train-v1")
                for r in read_rows(ROOT / f"data/training/{name}/train.jsonl")]
    guarded = list(training)
    for parent, catalog in (("data", "synthetic"), ("artifacts", "real")):
        for profile in ("launcher-basic-v1", "launcher-v1", "launcher-asr-v1"):
            for split in ("validation", "test"):
                path = ROOT / f"{parent}/benchmarks/{profile}/{catalog}/{split}.jsonl"
                if path.exists():
                    guarded.extend(read_rows(path))
    old_queries = {normalize_query(r["query"]) for r in guarded}
    old_groups = {r["group_id"] for r in guarded}
    old_targets = {r["expected_object_id"] for r in guarded}
    all_queries, datasets = set(), {}
    for profile in ("basic", "difficult"):
        dataset = []
        for index, case in enumerate(cases, 1):
            obj, query = case["object"], case[profile]
            key = normalize_query(query)
            family = (f"app-{index:02d}" if obj["kind"] == "app" else
                      "folder-drawings" if "чертежи" in obj["name"] else
                      "folder-measurements" if obj["kind"] == "folder" else "file-final-pdf")
            group = f"transfer-v1/{family}"
            require(key not in old_queries and key not in all_queries, "Query duplicates an existing source")
            require(group not in old_groups and obj["object_id"] not in old_targets, "Held-out identity overlaps")
            all_queries.add(key)
            dataset.append({"id": f"transfer-v1-{profile}-{index:02d}", "query": query,
                            "expected_action": "open", "expected_object_id": obj["object_id"],
                            "input_type": "text", "group_id": group, "tags": [profile, obj["kind"]],
                            "source": "authored", "rationale": f"Единственная цель по типу, назначению и уточнению: {obj['name']}. {obj['description']}"})
        datasets[profile] = dataset
    canonical = json.dumps(objects, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    catalog_hash = hashlib.sha256(canonical.encode()).hexdigest()
    OUTPUT.mkdir(parents=True, exist_ok=True)
    write_json(OUTPUT / "catalog.json", {"schema_version": 1, "catalog_hash": catalog_hash, "objects": objects})
    for profile, dataset in datasets.items():
        (OUTPUT / f"{profile}-test.jsonl").write_text(
            "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in dataset), encoding="utf-8")
    manifest = {"schema_version": 1, "dataset_id": "launcher-transfer-v1", "role": "test_only",
                "created_on": "2026-10-05", "author": "Codex", "catalog_hash": catalog_hash,
                "catalog_counts": dict(Counter(o["kind"] for o in objects)),
                "profiles": {p: {"rows": len(v), "groups": len({r["group_id"] for r in v}),
                                 "target_kinds": {"app": 35, "folder": 10, "file": 5}} for p, v in datasets.items()},
                "checkpoint_selection_access": False, "training_access": False,
                "guarded_source_rows": len(guarded), "model_evaluation": "Not evaluated during authoring",
                "annotation_review": {"status": "author_reviewed", "independent_human_review": False},
                "limits": "New authored fictional metadata/queries; related queries share groups. "
                          "Does not establish novel semantic concepts or human speech generalization.",
                "files": {name: hashlib.sha256((OUTPUT / name).read_bytes()).hexdigest() for name in
                          ("catalog.json", "basic-test.jsonl", "difficult-test.jsonl")}}
    write_json(OUTPUT / "manifest.json", manifest)
    print(json.dumps({"path": str(OUTPUT), "role": "test_only", "rows": 100,
                      "catalog_objects": 177, "guarded_source_rows": len(guarded), "evaluated": False}))


if __name__ == "__main__":
    prepare()
